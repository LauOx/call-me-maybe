def build_context_for_parameter(
        prompt: str, function: FunctionDefinition
        ) -> str:
    fn_name: str = function.name
    fn_description: str = function.description
    context: str = (
        'Selected function:\n'
        f'{fn_name}\n'
        f'Description:\n'
        f'{fn_description}\n'
        f'Parameters:\n'
    )
    for p_name, p_definition in function.parameters.items():
        context += f"- {p_name}: {p_definition.type}\n"
    context += (
        f'Request "{prompt}"\n'
        'Return a function call in JSON format with keys "name"'
        'and "parameters".\n'
        'Preserve the original spelling, capitalization, punctuation, '
        'and formatting of parameter values from the user request unless '
        'a transformation is explicitly requested.\n'
        f'\n{{"name": "{fn_name}", "parameters": {{'
    )
    return context


def preserve_literal_string_value(
    value: str,
    user_prompt: str
) -> str:
    """
    Preserve the exact text formatting of a generated string value.

    The function searches the original user prompt for a unique
    case-insensitive match of the generated value. If exactly one match
    is found, the original spelling and capitalization from the prompt
    are returned. Otherwise, the generated value is left unchanged.

    Args:
        value: String value generated by the model.
        user_prompt: Original natural-language request from the user.

    Returns:
        The matching text from the original prompt when a unique match
        exists, otherwise the original generated value.
    """
    if not value:
        return value
    pattern = re.escape(value)
    if value[0].isalnum():
        pattern = r"\b" + pattern
    if value[-1].isalnum():
        pattern = pattern + r"\b"
    matches = list(
        re.finditer(
            pattern,
            user_prompt,
            flags=re.IGNORECASE
        )
    )
    if len(matches) == 1:
        return matches[0].group(0)
    return value


def clean_param_value(text: str) -> str:
    """Clean spaces and ' from the string"""
    clean_spaces = text.strip()  
    return re.sub(r'\\+', r'\\', clean_spaces)


def clean_number(text: str) -> str:
    """Clean .000 from numbers"""
    clean: str = text.rstrip('0').rstrip('.')
    return clean
