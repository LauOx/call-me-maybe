class ParamType(Enum):
    NUMBER = "number"
    STRING = "string"
    BOOL = "boolean"
    INTEGER = "integer"
    FLOAT = "float"


class CandidateStatus(Enum):
    VALID_COMPLETE = "valid_complete"
    VALID_PREFIX = "valid_prefix"
    INVALID = "invalid"


def check_candidate_logits(
        candidate: str, allowed: list[str]
        ) -> CandidateStatus:
    """
    Check if context generated by the model is matching correctly
     the expected output"""
    for function_name in allowed:
        if candidate == function_name:
            return CandidateStatus.VALID_COMPLETE
        elif function_name.startswith(candidate):
            return CandidateStatus.VALID_PREFIX
    return CandidateStatus.INVALID


def is_valid_number(value: str) -> bool:
    """Check if a candidate is valid number"""
    try:
        float(value)
        return True
    except ValueError:
        return False


def is_bool(value: str) -> bool:
    """Check if a candidate is a valid boolean"""
    if value in 'False' or value in 'True':
        return True
    return False


def find_stop_char(token_text: str) -> str | None:
    """Busca el primer carácter de corte dentro del token, si existe"""
    for i, char in enumerate(token_text):
        if (
            char == 'Ċ' or
            char == '"' or
            ord(char) < 0x20
                ):
            return token_text[:i]  # lo que hay antes del carácter de corte
    return None  # no hay carácter de corte, todo el token es válido


def build_context_for_fn_name(
        functions: list[FunctionDefinition], prompt: str
        ) -> str:
    """Built a context text for finding correct function name"""
    functions_text = "\n".join(
            f"- {f.name}: {f.description}" for f in functions)
    context: str = (
        f"check function definition {functions_text} and"
        f"return a function name that solve this request: {prompt}."
        "Answer: "
        )
    return context


